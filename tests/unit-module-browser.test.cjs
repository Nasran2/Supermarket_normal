// Run with tests/Support/unit-browser-bootstrap.php and disposable SQLite servers.
// UNIT_TEST_DISABLED_URL defaults to :8139; UNIT_TEST_ENABLED_URL defaults to :8140.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const disabled = process.env.UNIT_TEST_DISABLED_URL || 'http://127.0.0.1:8139';
const enabled = process.env.UNIT_TEST_ENABLED_URL || 'http://127.0.0.1:8140';
const artifacts = __dirname + '/.browser-artifacts/unit-module';
fs.mkdirSync(artifacts, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const errors = [];
  const context = await browser.newContext({ viewport: { width: 1366, height: 900 } });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 500) errors.push(`${r.status()} ${r.url()}`); });
  const login = async base => {
    await page.goto(base + '/login');
    if (!page.url().endsWith('/login')) return;
    await page.locator('[name=login]').fill('admin');
    await page.locator('[name=password]').fill('password');
    await page.locator('button[type=submit]').click();
    await page.waitForURL(base + '/');
  };
  const noUnits = async () => assert.doesNotMatch(await page.locator('body').innerText(), /\b(?:units?|pcs|kg|kilogram|conversions?|doz)\b/i, page.url());
  try {
    await login(disabled);
    for (const path of ['/', '/manage/products', '/manage/products/create', '/manage/products/1', '/manage/products/1/edit', '/purchases/create', '/stock-adjustments/create', '/manage/roles/create', '/settings/receipt', '/reports/stock', '/reports/product-sales', '/reports/expiry', '/barcode', '/sales/1', '/sales/1/receipt', '/returns/sales/create?original_id=1', '/returns/sales/create?return_type=NO_RECEIPT', '/cheques', '/documentation', '/documentation/add-a-product', '/documentation/units-and-categories']) {
      await page.goto(disabled + path);
      await noUnits();
      assert.equal(await page.locator('[name=unit_id], #line-unit, [data-field=unit_id], [data-config=show_unit], [data-config=unit_font_size]').count(), 0, path);
    }
    for (const path of ['/manage/units', '/manage/unit-presets', '/manage/units/create', '/manage/unit-presets/create']) assert.equal((await page.request.get(disabled + path)).status(), 404);
    await page.goto(disabled + '/manage/products/create');
    const name = 'Browser New Soap ' + Date.now();
    await page.locator('form.product-editor [name=name]').fill(name);
    await page.locator('[name="opening_layers[0][quantity]"]').fill('10');
    await page.locator('[name="opening_layers[0][cost]"]').fill('100');
    await page.locator('[name="opening_layers[0][selling_price]"]').fill('130');
    await page.locator('form.product-editor button[type=submit]').click();
    await page.waitForURL(disabled + '/manage/products');
    await noUnits();
    await page.goto(disabled + '/manage/products/1/edit');
    await page.locator('form.product-editor [name=name]').fill('Browser Tomatoes Renamed');
    await page.locator('form.product-editor button[type=submit]').click();
    await page.waitForURL(disabled + '/manage/products');
    await page.goto(disabled + '/purchases/create');
    await page.locator('#supplier-search').fill('Browser supplier');
    await page.locator('.supplier-option').filter({ hasText: 'Browser supplier' }).click();
    await page.locator('#product-search').fill('Tomatoes');
    await page.locator('.product-option').filter({ hasText: 'Browser Tomatoes' }).click();
    await page.locator('[data-field=quantity]').fill('1.5');
    await noUnits();
    assert.equal(await page.locator('[data-field=quantity]').getAttribute('step'), '0.001');
    const layout = await page.locator('.purchase-line').evaluate(e => ({ columns: getComputedStyle(e).gridTemplateColumns.split(' ').length, overflow: e.scrollWidth > e.clientWidth + 1 }));
    assert.equal(layout.columns, 6);
    assert.equal(layout.overflow, false);
    await page.screenshot({ path: artifacts + '/purchase-disabled.png', fullPage: true });
    await page.locator('#save-purchase').click();
    await page.waitForURL(/\/purchases\/\d+$/);
    await noUnits();
    await page.goto(disabled + '/pos');
    await page.locator('[data-product="2"]').click();
    await page.locator('#price-choice-dialog').waitFor({ state: 'visible' });
    await noUnits();
    assert.equal(await page.locator('[data-price-choice]').count(), 2);
    await page.locator('[data-price-choice="0"]').click();
    await page.locator('.cart-item-name').first().click();
    await page.locator('#line-dialog').waitFor({ state: 'visible' });
    await noUnits();
    assert.equal(await page.locator('#line-unit').count(), 0);
    await page.locator('#line-quantity').fill('2');
    await page.locator('#line-form button[type=submit]').click();
    await page.locator('[data-product="3"]').click();
    await page.locator('#price-choice-dialog').waitFor({ state: 'visible' });
    await noUnits();
    assert.match(await page.locator('#price-choice-dialog').innerText(), /Expiry/);
    await page.locator('[data-price-choice="0"]').click();
    await page.screenshot({ path: artifacts + '/pos-disabled.png', fullPage: true });
    await page.locator('#open-payment').click();
    await page.locator('#payment-dialog').waitFor({ state: 'visible' });
    await page.locator('#exact-payment').click();
    await page.locator('#confirm-payment').click();
    await page.waitForFunction(() => document.querySelectorAll('.cart-line').length === 0);
    await page.goto(disabled + '/returns/sales/create?return_type=NO_RECEIPT');
    await page.locator('#nr-product-search').fill('Tomatoes');
    await page.locator('#nr-product-results button').first().click();
    await page.locator('[data-nr-next="2"]:visible').click();
    await page.locator('#nr-lines article').first().waitFor();
    await noUnits();
    assert.equal(await page.locator('#nr-lines label').filter({hasText: /^Unit$/}).count(), 0);
    await page.goto(disabled + '/sales/1');
    const returnButton = page.locator('[data-sale-dialog="sale-return-dialog"]');
    if (await returnButton.count()) {
      await returnButton.click();
      await page.locator('#sale-return-dialog').waitFor({state: 'visible'});
      await noUnits();
    }
    await page.goto(disabled + '/returns/sales/create?original_id=1');
    await page.locator('[data-return-next="2"]:visible').click();
    await page.locator('.return-qty').fill('1');
    await page.locator('#return-reason').selectOption({label: 'Wrong item'});
    await page.locator('[data-return-next="3"]:visible').click();
    await page.locator('[name=return_resolution][value=SAME]').check();
    await page.locator('.return-replacement-card').waitFor();
    await noUnits();
    await page.locator('[data-return-next="4"]:visible').click();
    await page.locator('#return-review-items p').first().waitFor();
    await noUnits();
    await page.locator('#return-complete').click();
    await page.waitForURL(/\/returns\/sales\/\d+$/);
    await noUnits();
    await page.goto(disabled + '/barcode');
    await page.locator('#barcode-search').fill('BROWSER-SOAP');
    await page.locator('[data-select]').first().check();
    await page.locator('[data-option]').selectOption({ index: 1 });
    await page.waitForFunction(() => document.querySelectorAll('#barcode-preview .barcode-label').length > 0);
    await noUnits();
    await page.screenshot({ path: artifacts + '/barcode-disabled.png', fullPage: true });
    for (const width of [390, 768]) {
      await page.setViewportSize({ width, height: 900 });
      await page.goto(disabled + '/purchases/create');
      await page.locator('#product-search').fill('Tomatoes');
      await page.locator('.product-option').filter({ hasText: 'Browser Tomatoes' }).click();
      assert.equal(await page.locator('.purchase-line').evaluate(e => e.scrollWidth > e.clientWidth + 1), false);
      await page.screenshot({ path: artifacts + `/purchase-disabled-${width}.png`, fullPage: true });
    }
    await page.setViewportSize({ width: 1366, height: 900 });
    await login(enabled);
    await page.goto(enabled + '/manage/products/1');
    assert.match(await page.locator('body').innerText(), /Kilogram/);
    assert.match(await page.locator('body').innerText(), /1000 g/);
    await page.goto(enabled + '/manage/products/create');
    assert.equal(await page.locator('[name=unit_id]').count(), 1);
    await page.goto(enabled + '/manage/units');
    assert.match(await page.locator('body').innerText(), /Units/);
    await page.goto(enabled + '/manage/unit-presets');
    assert.match(await page.locator('body').innerText(), /Multiple units/);
    await page.goto(enabled + '/pos');
    assert.equal(await page.locator('#line-unit').count(), 1);
    await page.goto(enabled + '/barcode');
    assert.equal(await page.locator('[data-config=show_unit]').count(), 1);
    const basic = process.env.UNIT_TEST_BASIC_URL || 'http://127.0.0.1:8141';
    await login(basic);
    await page.goto(basic + '/manage/products/create');
    assert.equal(await page.locator('[name=unit_id], [name=barcode], #track-expiry').count(), 0);
    await noUnits();
    await page.goto(basic + '/pos');
    await page.locator('[data-product="1"]').click();
    await page.locator('.cart-item-name').first().waitFor();
    await noUnits();
    await page.locator('#open-payment').click();
    await page.locator('#payment-dialog').waitFor({state:'visible'});
    await page.locator('#exact-payment').click();
    await page.locator('#confirm-payment').click();
    await page.waitForFunction(() => document.querySelectorAll('.cart-line').length === 0);
    assert.deepEqual(errors, []);
    console.log('Browser checks passed: quantity-only forms, product create/edit, decimal purchase, POS price/expiry choices, cart editing and checkout, labels, responsive layouts, routes and re-enabling preserved units/conversions.');
  } finally {
    if (errors.length) console.error('Browser errors:', errors);
    await context.close();
    await browser.close();
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
